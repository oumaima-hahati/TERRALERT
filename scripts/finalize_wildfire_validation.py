#!/usr/bin/env python3
"""Generate the final TERRALERT historical FWI validation report."""

from pathlib import Path
import subprocess
import sys
import pandas as pd

BASE = Path("data/wildfires/processed")
REPORT = Path("docs/WILDFIRE_FWI_FINAL_VALIDATION.md")

fwi = pd.read_csv(
    BASE / "wildfire_fwi_nasa_chirps_2001_2025.csv"
)

fires = pd.read_csv(
    BASE / "firms_fwi_comparison_nasa_chirps.csv"
)

assert len(fwi) == 100441
assert len(fires) == 177
assert fwi["commune"].nunique() == 11
assert not fwi.duplicated(["commune", "date"]).any()

assert pd.to_datetime(fwi["date"]).dt.year.min() == 2001
assert pd.to_datetime(fwi["date"]).dt.year.max() == 2025

matched = fires[fires["comparison_status"] == "matched"]
unmatched = fires[
    fires["comparison_status"] == "no_weather_overlap"
]

assert len(matched) == 165
assert len(unmatched) == 12
assert matched["fwi"].notna().all()

high_levels = ["High", "Very High", "Extreme"]
high_count = int(
    matched["danger_level"].isin(high_levels).sum()
)

evaluations = [
    ("Overall historical comparison",
     "scripts/evaluate_fwi_nasa_chirps.py"),
    ("Seasonally matched comparison",
     "scripts/evaluate_fwi_seasonal_baseline.py"),
    ("Local seasonal comparison",
     "scripts/evaluate_fwi_local_baseline.py"),
]

sections = []

for title, script in evaluations:
    print(f"Running: {script}", flush=True)

    result = subprocess.run(
        [sys.executable, script],
        text=True,
        capture_output=True
    )

    if result.returncode != 0:
        print(result.stdout)
        print(result.stderr, file=sys.stderr)
        raise SystemExit(
            f"FAILED: {script} returned {result.returncode}"
        )

    sections.append(
        f"## {title}\n\n"
        f"Generated by `{script}`:\n\n"
        f"```text\n{result.stdout.strip()}\n```\n"
    )

report = f"""# TERRALERT — Final Historical Wildfire FWI Validation

## 1. Scope

Historical fire-weather danger assessment for the 11 TERRALERT
study areas in Tanger–Assilah, Morocco.

Period: 2001–2025.

Status: **Research baseline implemented and retrospectively evaluated.**

This is not an operational wildfire prediction certification.

## 2. Data and methodology

- Temperature, humidity and wind: NASA POWER hourly data.
- Precipitation: CHIRPS v3 daily satellite precipitation.
- Historical fire detections: NASA FIRMS.
- Indicator: Canadian Fire Weather Index (FWI).
- FWI calculated with continuous moisture-code states and
  an initial warm-up period.
- Fire detections compared with commune-level FWI.
- Additional comparisons made against seasonal and local
  reference conditions.

The rainfall timing and meteorological sampling are
approximations and require further independent validation.

## 3. Verified dataset checks

| Indicator | Result |
|---|---:|
| Daily commune FWI records | {len(fwi):,} |
| Study areas | {fwi["commune"].nunique()} |
| FIRMS vegetation detections | {len(fires)} |
| Matched detections | {len(matched)} |
| Detections outside weather coverage | {len(unmatched)} |
| Matched detections with High+ FWI | {high_count} |
| Matched detections with High+ FWI (%) | {100*high_count/len(matched):.2f}% |

These percentages describe the sampled historical satellite
detections, not forecast accuracy.

## 4. Retrospective evaluation

"""

report += "\n\n".join(sections)

report += """

## 5. Scientific limitations

1. FIRMS detections are not a complete inventory of fires.
   A day with no detection is not proof of no fire.
2. Repeated satellite detections of the same incident
   must not be treated as independent fire events.
3. Commune-level FWI is a coarse weather-danger indicator,
   not a parcel-level ignition probability.
4. NASA POWER weather estimates may be shared by
   neighboring communes, limiting spatial independence.
5. CHIRPS calendar-day precipitation approximates
   the precipitation timing required by standard FWI.
6. High FWI also occurs on many days without detected fires.
7. Retrospective association and baseline comparisons
   do not establish prospective predictive performance.
8. No independent weather-station calibration,
   full fire-event ground truth, or operational
   warning-policy validation has been demonstrated.

## 6. Conclusion

The historical FWI processing, retrospective FIRMS
comparison, baseline evaluations and historical GIS
outputs support completion of the TERRALERT
**research-baseline implementation and evaluation**.

Operational wildfire alerts must remain provisional
until independently validated and authorized.

## 7. Dependencies for future validation

- Independent meteorological observations for calibration.
- A more complete, independently reviewed fire-event inventory.
- Prospective forecast verification and agreed alert thresholds.
- Integration and review with other TERRALERT components.

These are future validation dependencies, not prerequisites
for closing the historical research-baseline task.
"""

REPORT.parent.mkdir(parents=True, exist_ok=True)
REPORT.write_text(report, encoding="utf-8")

print("\n=== FINAL WILDFIRE VALIDATION ===")
print("Historical records:", len(fwi))
print("Matched FIRMS detections:", len(matched))
print("High+ matched detections:", high_count)
print("Evaluation scripts: 3/3 passed")
print("Report:", REPORT)
print("\nSUCCESS: Final validation report generated!")
